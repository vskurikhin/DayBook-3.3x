// Package contract — базовый пакет доменных типов и контрактов протокола Raft.
//
// Пакет содержит общие типы и интерфейсы, которые используют одновременно
// ядро (корневой пакет) и пакеты реализаций (хранилище и транспорт):
// типы журнала и RPC, конфигурацию кластера, интерфейсы хранилища,
// хранилища снимков и транспорта, а также маркерные ошибки протокола —
// заранее определённые значения, сигнализирующие о типовых состояниях
// (таймауты, потеря лидера и т. п.).
//
// Пакет является листовым: он импортирует только стандартную библиотеку и
// не зависит ни от корневого пакета, ни от пакетов реализаций. Направление
// зависимостей — от ядра и пакетов реализаций к этому пакету, что позволяет
// разорвать импорт-циклы между ними.
//
// Корневой пакет сохраняет публичный API через прозрачные type-алиасы и
// const-переэкспорты; маркерные ошибки которые используются потребителями
// непосредственно через квалификатор contract.Err*, без переэкспорта.
