// Package transp — реализации транспорта RPC для протокола Raft.
//
// Пакет предоставляет две реализации контракта
// Transport (pkg/raft/contract):
//   - сетевой транспорт поверх TCP с gob-сериализацией (TCPTransport)
//   - внутрипроцессовый транспорт для тестов (InmemTransport).
//
// Типы RPC регистрируются в encoding/gob с закреплёнными метками сериализации —
// полным путём импорта корневого пакета github.com/vskurikhin/raft.
// Метки являются частью контракта сериализации: их изменение или удаление
// нарушило бы декодирование RPC между узлами разных версий, поэтому они
// защищены постоянным golden-тестом.
//
// Пакет зависит только от базового пакета контрактов (contract) и стандартной
// библиотеки. Тесты пакета дополнительно импортируют корневой пакет raft.
