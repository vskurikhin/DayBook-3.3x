package raft

import (
	"context"
	"errors"
	"os"
	"sync/atomic"
	"time"

	"github.com/vskurikhin/raft/internal/tracelog"
)

// _traceCM — порог детализации отладочных сообщений консенсус-модуля
// (traceLogfLocked, traceSprintfLocked, traceLogf). Сообщение с уровнем
// level выводится, если _traceCM > level. Значение задаётся полем
// TraceConfig.Level единственного успешного вызова SetTrace, по умолчанию 0.
// Изменяется только до старта горутин.
var _traceCM = 0

// traceQueueCapacity — ёмкость очереди процессного писателя трассировки:
// ограничено число сообщений, а не занимаемая ими память. Значение
// передаётся конструктору tracelog.New; сам механизм очереди и его
// неэкспортируемые детали живут в пакете tracelog.
const traceQueueCapacity = 4096

// _traceWriter — процессный писатель трассировки консенсус-модуля.
// Создаётся единственным успешным вызовом SetTrace при положительном
// пороге и после этого неизменен; при выключенной трассировке равен nil.
var _traceWriter *tracelog.Writer

// traceEnabled сообщает, будет ли сообщение уровня level напечатано
// трассировкой. Единственный источник истины для порога _traceCM.
func traceEnabled(level int) bool { return level < _traceCM }

// Уровни сообщений трассировки консенсус-модуля (порог _traceCM:
// сообщение уровня l печатается, если l < _traceCM). Уровни — ступени
// подробности: увеличение порога добавляет новый слой сообщений,
// не отключая предыдущие. Значения и состав ступеней — операционный
// контракт вывода, они не меняются.
const (
	// _traceLevelKeyEvents — ключевые события: смена роли и терма,
	// отправка и приём RequestVote, TimeoutNow, отказы отправки
	// и создания снимка. Печатаются при пороге от 1.
	_traceLevelKeyEvents = 0

	// _traceLevelLoops — течение циклов выборов и лидера: таймер
	// выборов, входы и выходы из циклов, шаг вниз лидера.
	// Печатаются при пороге от 2.
	_traceLevelLoops = 1

	// _traceLevelProgress — результативные события: победа
	// в выборах, продвижение индекса фиксации, длительность
	// персиста. Печатаются при пороге от 3.
	_traceLevelProgress = 2

	// _traceLevelPreVote — предварительное голосование: отправка,
	// отказы и тайм-ауты pre-vote, причины отказов в голосах;
	// детали отправки снимка ведомому. Печатаются при пороге от 5.
	_traceLevelPreVote = 4

	// _traceLevelReplication — репликация: обработка RPC (handleRPC,
	// AppendEntries и ответы), отправка AppendEntries, пульс.
	// Печатаются при пороге от 9.
	_traceLevelReplication = 8

	// _traceLevelLogDump — полный дамп журнала после изменения.
	// Печатается при пороге от 17.
	_traceLevelLogDump = 16
)

// _traceConfigured — сторожевой флаг строгого set-once: единственная
// успешная конфигурация трассировки на процесс уже выполнена.
// Устанавливается только успешным вызовом SetTrace
// (вызов, завершившийся ошибкой I/O, окно не расходует).
var _traceConfigured atomic.Bool

// _traceCMCreated — сторожевой флаг: в процессе уже создавался
// ConsensusModule. Устанавливается конструктором.
var _traceCMCreated atomic.Bool

// TraceConfig — параметры трассировки консенсус-модуля, передаваемые
// SetTrace. Тип является простым носителем значений: у него нет методов
// и он не подразумевает расширения поведением.
type TraceConfig struct {
	// Level — порог детализации: сообщение уровня l печатается, если
	// l < Level. Level == 0 означает, что трассировка выключена;
	// нулевое значение НЕ трактуется как «уровень по умолчанию 1».
	Level int

	// LogFile — путь к файлу журнала трассировки. Файл открывается в
	// режиме добавления и создаётся при необходимости. Пустая строка
	// означает вывод в поток ошибок (os.Stderr), захваченный в момент
	// вызова SetTrace; перенастройка log.SetOutput на трассировку
	// консенсус-модуля больше не влияет.
	LogFile string
}

// SetTrace конфигурирует трассировку консенсус-модуля (traceLogfLocked,
// traceSprintfLocked, traceLogf): порог детализации cfg.Level и назначение
// вывода cfg.LogFile. Пустой cfg.LogFile — вывод напрямую в захваченный
// os.Stderr; иначе файл открывается в режиме добавления и создаётся при
// необходимости. Значение cfg.Level == 0 выключает трассировку и не
// подменяется значением по умолчанию.
//
// Контракт (строгий set-once-before-first-CM): функция успешна ровно
// один раз на процесс, до создания первого ConsensusModule (и, тем
// самым, до входа CM в Candidate/Candidate-Modifier). Первый успешный
// вызов выигрывает и замораживает конфигурацию — и приёмник, и порог;
// состояние трассировки после этого read-only. Любой повторный вызов —
// детерминированная ошибка контракта, в том числе до создания CM;
// вызов после создания CM — та же ошибка. Вызов, завершившийся ошибкой
// I/O, окно конфигурации не расходует и не изменяет состояние
// трассировки.
//
// При cfg.Level > 0 успешный вызов запускает горутину писателя до
// возврата; при Level <= 0 горутина не создаётся. Завершение процесса
// выполняет ShutdownTrace; до него вызовы FlushTrace/ShutdownTrace
// управляют только писателем, не порогом и не приёмником.
func SetTrace(cfg TraceConfig) error {
	if _traceConfigured.Load() || _traceCMCreated.Load() {
		return errors.New(
			"raft: trace configuration must be set exactly once, " +
				"before the first ConsensusModule is created; repeated " +
				"calls are forbidden",
		)
	}
	if cfg.LogFile == "" {
		if cfg.Level > 0 {
			_traceWriter = tracelog.New(os.Stderr, traceQueueCapacity, time.Now)
		}
		_traceCM = cfg.Level
		_traceConfigured.Store(true)
		return nil
	}
	// Порог и писатель подключаются только после успешного открытия
	// файла: вызов, завершившийся ошибкой I/O, окно конфигурации не
	// расходует и обязан оставить состояние трассировки прежним.
	f, err := os.OpenFile(cfg.LogFile, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o600)
	if err != nil {
		return err
	}
	if cfg.Level <= 0 {
		// Трассировка выключена: писатель не создаётся, дескриптор
		// вывода не нужен. Файл остаётся созданным, как и раньше.
		_ = f.Close()
		_traceCM = cfg.Level
		_traceConfigured.Store(true)
		return nil
	}
	_traceWriter = tracelog.New(f, traceQueueCapacity, time.Now)
	_traceCM = cfg.Level
	_traceConfigured.Store(true)
	return nil
}

// FlushTrace ожидает записи всех сообщений трассировки, принятых до
// вызова, и возвращает первую накопленную ошибку записи. Непрерывные
// новые постановки границу не расширяют: успех относится к префиксу
// очереди до поставленного маркера включительно.
//
// Контекст ненулевой и ограничивает только ожидание: отмена после
// постановки маркера его не удаляет. Вызов является операцией владельца
// процесса и запрещён под cm.mu, из часов и приёмника писателя, а также
// из хелперов трассировки. При выключенной трассировке возвращается nil.
func FlushTrace(ctx context.Context) error {
	w := _traceWriter
	if w == nil {
		return nil
	}
	return w.Flush(ctx)
}

// ShutdownTrace останавливает горутину писателя и ожидает записи всего
// принятого до остановки, возвращая первую накопленную ошибку записи.
// Файл не закрывается: он нужен последующим синхронным постановкам.
// Повторные вызовы безопасны и ждут ту же остановку. Вызов является
// операцией владельца процесса; при выключенной трассировке возвращается
// nil без запуска горутины.
//
// Гарантия сохранности хвоста относится к штатному завершению процесса:
// при аварии (panic в чужой горутине, runtime fatal, внутренний вызов
// log.Fatal, SIGKILL, сбой питания) гарантий записи нет.
func ShutdownTrace(ctx context.Context) error {
	w := _traceWriter
	if w == nil {
		return nil
	}
	return w.Shutdown(ctx)
}
